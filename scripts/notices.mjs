// Generates THIRD_PARTY_NOTICES.txt from what is actually bundled: esbuild's metafile lists every
// node_modules package in the client and server bundles; their license texts are copied verbatim.
// Also covers the self-hosted assets that are not bundled (Inter font, Lucide icons).
//   node scripts/notices.mjs   (runs automatically in `npm run build`)
import { build } from "esbuild";
import { readFile, writeFile, readdir } from "node:fs/promises";
import path from "node:path";

const common = { bundle: true, write: false, metafile: true, logLevel: "silent", loader: { ".css": "text", ".pdf": "binary" }, define: { __RESTRICTED_HOST__: "false", __DEMO__: "false", "process.env.NODE_ENV": '"production"' } };
const client = await build({ ...common, entryPoints: ["src/ui/main.tsx"], format: "esm", jsx: "automatic", outdir: "out", splitting: true });
const server = await build({ ...common, entryPoints: ["server/server.ts", "server/vercel.ts"], platform: "node", format: "esm", outdir: "out" });

const pkgs = new Map();
for (const meta of [client.metafile, server.metafile]) {
  for (const input of Object.keys(meta.inputs)) {
    const m = input.replace(/\\/g, "/").match(/node_modules\/((?:@[^/]+\/)?[^/]+)/g);
    if (!m) continue;
    const last = m[m.length - 1].replace("node_modules/", "");
    const dir = input.slice(0, input.lastIndexOf(m[m.length - 1]) + m[m.length - 1].length);
    pkgs.set(last, dir);
  }
}

async function licenseText(dir) {
  try {
    const files = await readdir(dir);
    const f = files.find((x) => /^(licen[cs]e|copying)(\.|$)/i.test(x));
    return f ? (await readFile(path.join(dir, f), "utf8")).trim() : null;
  } catch {
    return null;
  }
}

const sections = [];
for (const [name, dir] of [...pkgs].sort((a, b) => a[0].localeCompare(b[0]))) {
  const pj = JSON.parse(await readFile(path.join(dir, "package.json"), "utf8"));
  const text = await licenseText(dir);
  sections.push(`${pj.name}@${pj.version}, ${pj.license || "see license text"}\n${pj.homepage || (pj.repository && (pj.repository.url || pj.repository)) || ""}\n\n${text || `License: ${pj.license}`}`);
}

const extra = [
  `Inter font (self-hosted, subset), SIL Open Font License 1.1\nhttps://github.com/rsms/inter\nCopyright 2016 The Inter Project Authors. Full text: public/fonts/LICENSE-Inter.txt`,
  `Lucide icons (via react-icons), ISC\nhttps://lucide.dev, https://github.com/lucide-icons/lucide/blob/main/LICENSE`,
];

const out = `THIRD-PARTY SOFTWARE NOTICES | FLOWSTATE\nGenerated by scripts/notices.mjs from the production bundles. Do not edit by hand.\n\n${[...sections, ...extra].map((s) => `${"=".repeat(78)}\n${s}`).join("\n\n")}\n`;
await writeFile("THIRD_PARTY_NOTICES.txt", out);
console.log(`THIRD_PARTY_NOTICES.txt: ${pkgs.size} bundled packages + ${extra.length} self-hosted assets`);
